// Bakes the songs (songs.js, scores in ../songs/*.txt) into ../song-clips.js as Opus data: URIs, sung by DECtalk.
//
//   node plugins/buddy/tools/render-songs.mjs
//
// Run it when a song changes. Needs ffmpeg with libopus on PATH and the dev dependency
// @echogarden/dectalk-wasm. DECtalk can't run inside the plugin (its WASM build needs
// threads and Workers), so this is offline only and song-clips.js is committed.
import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { DecTalkVoice, synthesize } from "@echogarden/dectalk-wasm";
import { SONGS } from "../songs.js";

const dir = mkdtempSync(join(tmpdir(), "buddy-songs-"));
const clips = {};
try {
  for (const { title, file } of SONGS) {
    // The scores switch voices mid-song ([:np] Paul, [:nk] Kit, [:nb] Betty...). Drop those so
    // every song is sung by one voice, set below.
    const markup = readFileSync(fileURLToPath(new URL(`../songs/${file}.txt`, import.meta.url)), "utf8")
      .replace(/:n[a-z]\b/g, "")
      .replace(/\[\s*\]/g, "");
    const wav = join(dir, "in.wav");
    const ogg = join(dir, "out.ogg");
    writeFileSync(wav, await synthesize(markup, { voice: DecTalkVoice.Paul, rate: 150 }));
    execFileSync("ffmpeg", ["-y", "-loglevel", "error", "-i", wav, "-ac", "1", "-c:a", "libopus", "-b:a", "32k", ogg]);
    const bytes = readFileSync(ogg);
    clips[title] = "data:audio/ogg;base64," + bytes.toString("base64");
    console.log(`${String(bytes.length).padStart(6)} B  ${title}`);
  }
} finally {
  rmSync(dir, { recursive: true, force: true });
}
writeFileSync(
  fileURLToPath(new URL("../song-clips.js", import.meta.url)),
  "// Generated by tools/render-songs.mjs. Do not edit.\nexport default " + JSON.stringify(clips, null, 1) + ";\n",
);
