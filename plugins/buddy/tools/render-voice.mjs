// Bakes the fixed lines (lines.js) into ../voice.js as small Opus data: URIs.
//
//   node plugins/buddy/tools/render-voice.mjs
//
// Asks tetyys.com's SAPI4 service once per line, so run it when the lines or the
// BAKED voice change, not on every build. Needs ffmpeg with libopus on PATH.
// This is a maintainer tool only: voice.js is committed, so `lune ci` and anyone
// installing the plugin never touch ffmpeg.
import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { ALL, BAKED } from "../lines.js";

const dir = mkdtempSync(join(tmpdir(), "buddy-"));
const clips = {};
let total = 0;

try {
  for (const text of [...new Set(ALL)]) {
    const url =
      "https://www.tetyys.com/SAPI4/SAPI4?text=" +
      encodeURIComponent(text) +
      `&voice=${encodeURIComponent(BAKED.voice)}&pitch=${BAKED.pitch}&speed=${BAKED.speed}`;

    // the free service 503s now and then: retry with a growing wait before giving up
    let res;
    for (let tries = 1; ; tries++) {
      res = await fetch(url);
      if (res.ok || tries === 5) break;
      await new Promise((r) => setTimeout(r, tries * 4000));
    }
    if (!res.ok) throw new Error(`${res.status} for "${text}": ${await res.text()}`);

    const wav = join(dir, "in.wav");
    const ogg = join(dir, "out.ogg");
    writeFileSync(wav, Buffer.from(await res.arrayBuffer()));
    // mono, 24 kHz, 32 kbps: close to the service's own 22 kHz output, ~4 KB per second
    execFileSync("ffmpeg", ["-y", "-loglevel", "error", "-i", wav, "-ac", "1", "-ar", "24000", "-c:a", "libopus", "-b:a", "32k", ogg]);

    const bytes = readFileSync(ogg);
    total += bytes.length;
    clips[text] = "data:audio/ogg;base64," + bytes.toString("base64");
    console.log(`${String(bytes.length).padStart(6)} B  ${text}`);
    await new Promise((r) => setTimeout(r, 1000)); // be polite to a free service
  }
} finally {
  rmSync(dir, { recursive: true, force: true });
}

const out = fileURLToPath(new URL("../voice.js", import.meta.url));
writeFileSync(out, "// Generated by tools/render-voice.mjs. Do not edit.\nexport default " + JSON.stringify(clips, null, 1) + ";\n");
console.log(`\nwrote voice.js: ${Object.keys(clips).length} clips, ${(total / 1024).toFixed(1)} KB of audio`);
